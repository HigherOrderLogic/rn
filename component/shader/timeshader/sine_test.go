func TestSine(t *testing.T) {
	sh := new(nopShader)

	tsuite := []struct {
		name        string
		revolutions float64
		total       int
		frameIn     int
		frameOut    int
	}{
		{
			name:        "first frame stays first frame",
			revolutions: 1.0,
			total:       101,
			frameIn:     0,
			frameOut:    0,
		},
		{
			name:        "last frame becomes first frame",
			revolutions: 1.0,
			total:       101,
			frameIn:     100,
			frameOut:    0,
		},
		{
			name:        "middle frame becomes first frame",
			revolutions: 1.0,
			total:       101,
			frameIn:     50,
			frameOut:    0,
		},
		{
			name:        "frame in quarter duration becomes last frame",
			revolutions: 1.0,
			total:       101,
			frameIn:     25,
			frameOut:    100, // FIX: 101
		},
		{
			name:        "two revolutions cycles full wave twice",
			revolutions: 2.0,
			total:       101,
			frameIn:     int(math.Round(float64(5) / float64(8) * float64(101))),
			frameOut:    100,
		},

		{
			name:        "half revolution makes half wave peaking highest at mid-duration",
			revolutions: 0.5,
			total:       101,
			frameIn:     50,
			frameOut:    100,
		},
		{
			name:        "negative number loops backward",
			revolutions: 1.0,
			total:       101,
			frameIn:     -50,
			frameOut:    0,
		},
	}

	for _, tcase := range tsuite {
		t.Run(tcase.name, func(t *testing.T) {
			defer sh.reset()
			ts := Sine(sh, tcase.revolutions)
			ts.Shade(tcase.frameIn, tcase.total, [][]term.Cell{})
			require.True(t, sh.shadeCalled)
			assert.Equal(t, tcase.frameOut, sh.frame)
		})
	}
}
